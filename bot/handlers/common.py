from aiogram import Router, F
from aiogram.filters import Command
from aiogram.types import Message
from bot.services.week_service import format_week_header

router = Router()


@router.message(Command("help"))
@router.message(F.text == "ℹ️ Допомога")
async def show_help(message: Message):
    """Відображення інструкцій та довідки."""
    week_info_text = format_week_header()

    help_text = (
        f"ℹ️ <b>Довідка щодо використання бота розкладу</b>\n\n"
        f"{week_info_text}\n\n"
        f"🤖 <b>Основні можливості:</b>\n"
        f"• <b>Індивідуальний розклад</b>: бот автоматично комбінує предмети вашої академічної групи (ОПП) та окремої групи з англійської мови.\n"
        f"• <b>Розрахунок тижнів</b>: 1-й тиждень семестру розпочинається з <b>01.09.2026</b>, бот автоматично чергує чисельник та знаменник.\n"
        f"• <b>Нагадування</b>: бот автоматично надсилає сповіщення перед початком кожної пари (назва, тип, викладач, аудиторія або посилання на відеозустріч).\n\n"
        f"📌 <b>Команди та навігація:</b>\n"
        f"• 📅 <b>Сьогодні</b> (/today) — розклад на поточний день.\n"
        f"• 🗓️ <b>Завтра</b> (/tomorrow) — розклад на наступний день.\n"
        f"• 📆 <b>На тиждень</b> (/week) — розклад на весь робочий тиждень з можливістю перемикання між 1-м та 2-м тижнями.\n"
        f"• ⏳ <b>Зараз</b> (/now) — інформація про поточну пару та наступну заплановану.\n"
        f"• ⚙️ <b>Налаштування</b> (/settings) — зміна ОПП групи, групи англійської або часу нагадування.\n"
        f"• /start — перезапустити майстер налаштування або оновити стан."
    )
    await message.answer(help_text, parse_mode="HTML")
